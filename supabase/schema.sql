create table if not exists usuario (
  id integer generated by default as identity primary key,
  nome text not null,
  senha text not null,
  telefone text not null,
  email text not null unique,
  created_at timestamptz default now()
);

create table if not exists figurinhas (
  id integer generated by default as identity primary key,
  usuario_id integer not null references usuario(id) on delete cascade,
  time text not null,
  categoria integer not null check (categoria in (50, 60, 70)),
  nome_jogador text not null,
  quantidade integer not null default 0,
  created_at timestamptz default now()
);

alter table usuario disable row level security;
alter table figurinhas disable row level security;

create index if not exists figurinhas_usuario_id_idx on figurinhas(usuario_id);
